import { spawn, type ChildProcess } from 'node:child_process'
import { promises as fs } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { pipeline } from 'node:stream/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../..', import.meta.url))
const image = 'mcr.microsoft.com/playwright:v1.64.0-noble@sha256:06a9939e57531807f8d5fd76ce44b53165ffb7d7501d87ab10e285c20b1e971f'
const version = '1.64.0'
const device = '/dev/dri/renderD128'
const label = 'org.tsepistle.ci.owner'
// Playwright 1.64 bundles its registry; inspect the actual selected binary.
const browserInfoScript = `
const fs = require('node:fs')
const { execFileSync } = require('node:child_process')
const packages = '/tmp/runner/node_modules/'
for (const name of ['@playwright/test', 'playwright', 'playwright-core']) {
  if (require(packages + name + '/package.json').version !== ${JSON.stringify(version)}) throw Error('Version mismatch')
}
const browser = require(packages + 'playwright-core/browsers.json').browsers.find(browser => browser.name === 'chromium-headless-shell')
if (!browser?.revision || !browser.browserVersion) throw Error('Browser pin missing')
const executable = require(packages + 'playwright-core/lib/coreBundle.js').registry.registry.findExecutable('chromium-headless-shell').executablePath()
if (!executable.startsWith('/ms-playwright/')) throw Error('Unexpected browser path')
fs.accessSync(executable, fs.constants.X_OK)
const actualVersion = execFileSync(executable, ['--version'], { encoding: 'utf8', timeout: 5000 }).trim()
if (!actualVersion.endsWith(' ' + browser.browserVersion)) throw Error('Installed browser version mismatch')
console.log(JSON.stringify({ ...browser, executable, actualVersion }))
`
const required = (key: string): string => {
  const value = process.env[key]
  if (!value) throw new Error(`Hardware browser requires bound ${key}.`)
  return value
}
const namespace = required('WIKI_TEST_NAMESPACE')
const owner = required('WIKI_CI_RESOURCE_OWNER')
const artifacts = required('WIKI_LOCAL_CI_ARTIFACTS')
required('WIKI_LOCAL_CI_ACTIVE_PHASE')
const phaseRunner = required('WIKI_LOCAL_CI_PHASE_RUNNER')
required('PLAYWRIGHT_BASE_URL')
if (!/^tsepistle-ci-[a-z0-9][a-z0-9-]{0,98}$/.test(namespace) || !path.isAbsolute(artifacts) || !path.isAbsolute(phaseRunner))
  throw new Error('Invalid bound hardware browser namespace or artifact/resource path.')
if (Bun.version !== '1.4.3') throw new Error('Hardware launcher requires pinned Bun 1.4.3.')
if (process.env.PLAYWRIGHT_HARDWARE_WS_ENDPOINT) throw new Error('Hardware endpoint must be generated by the isolated launcher.')
const name = `${namespace}-hardware-browser`
const network = `${namespace}-network`
const directory = path.join(artifacts, 'e2e/core/hardware-webgl2')
let interrupted = 0
const active = new Set<ChildProcess>()
const interrupt = (): void => {
  interrupted = 130
  for (const child of active) child.kill('SIGINT')
}
const terminate = (): void => {
  interrupted = 143
  for (const child of active) child.kill('SIGTERM')
}
process.on('SIGINT', interrupt)
process.on('SIGTERM', terminate)

async function command(args: string[], timeout = 30_000, allowFailure = false): Promise<string> {
  const child = spawn(args[0]!, args.slice(1), { cwd: root, env: process.env, stdio: ['ignore', 'pipe', 'pipe'] })
  active.add(child)
  let output = '',
    errorOutput = ''
  let expired = false
  const timer = setTimeout(() => {
    expired = true
    child.kill('SIGKILL')
  }, timeout)
  child.stdout!.on('data', (chunk: Buffer) => {
    output = (output + chunk.toString()).slice(-65_536)
  })
  child.stderr!.on('data', (chunk: Buffer) => {
    errorOutput = (errorOutput + chunk.toString()).slice(-8192)
  })
  try {
    const { promise, resolve, reject } = Promise.withResolvers<number | null>()
    child.once('error', reject)
    child.once('close', resolve)
    const code = await promise
    if (expired || (code !== 0 && !allowFailure))
      throw new Error(`${args[0]} ${args[1]} failed${expired ? ' (timeout)' : ''}: ${errorOutput.replace(/ws:\/\/\S+/g, '[endpoint]')}`)
    return code === 0 ? output.trim() : ''
  } finally {
    clearTimeout(timer)
    active.delete(child)
  }
}

// Each archive is streamed independently, with dependency resolution flattened only
// after resolving from its actual parent package (never the production root core).
async function transfer(containerId: string, source: string, destination: string): Promise<void> {
  await command(['docker', 'exec', containerId, 'mkdir', '-p', destination])
  const tar = spawn('tar', ['--exclude=./node_modules', '-C', source, '-cf', '-', '.'], { stdio: ['ignore', 'pipe', 'inherit'] })
  const extract = spawn('docker', ['exec', '-i', containerId, 'tar', '-xf', '-', '-C', destination], { stdio: ['pipe', 'ignore', 'inherit'] })
  active.add(tar)
  active.add(extract)
  const timer = setTimeout(() => {
    tar.kill('SIGKILL')
    extract.kill('SIGKILL')
  }, 60_000)
  const exited = (child: ChildProcess): Promise<void> => {
    const { promise, resolve, reject } = Promise.withResolvers<void>()
    child.once('error', reject)
    child.once('close', code => (code === 0 ? resolve() : reject(new Error('Pinned Playwright package transfer failed.'))))
    return promise
  }
  try {
    await Promise.all([exited(tar), exited(extract), pipeline(tar.stdout!, extract.stdin!)])
  } finally {
    clearTimeout(timer)
    active.delete(tar)
    active.delete(extract)
    tar.kill()
    extract.kill()
  }
}

function hardwareArgs(input: string[]): string[] {
  const result: string[] = []
  const owned: Record<string, true> = { '--output': true, '-o': true, '--project': true, '--workers': true, '-j': true, '--retries': true }
  for (let index = 0; index < input.length; index++) {
    const arg = input[index]!
    const key = arg.split('=')[0]!
    if (Object.hasOwn(owned, key)) {
      if (!arg.includes('=')) index++
      continue
    }
    if (/^-[oj].+/.test(arg) || arg === '--no-deps') continue
    if (arg === '--' || key === '--config' || key === '-c' || key === '--ui' || key === '--debug' || key === '--headed')
      throw new Error(`Hardware launcher does not permit ${key}.`)
    result.push(arg)
  }
  return [...result, '--project=performance-webgl2', '--no-deps', '--workers=1', '--retries=0', `--output=${path.join(directory, 'test-results')}`]
}

let containerId = ''
let creationAttempted = false
let status = 1
const metadata: Record<string, unknown> = {
  image,
  playwrightVersion: version,
  bunVersion: Bun.version,
  device,
  limits: { memoryBytes: 2147483648, memorySwapBytes: 2147483648, cpus: 8, pids: 256, shmBytes: 134217728, tmpfsBytes: 1073741824 }
}
try {
  const args = hardwareArgs(process.argv.slice(2))
  const require = createRequire(import.meta.url)
  const testPackage = require.resolve('@playwright/test/package.json')
  const playwrightPackage = createRequire(testPackage).resolve('playwright/package.json')
  const corePackage = createRequire(playwrightPackage).resolve('playwright-core/package.json')
  const packages = [
    ['@playwright/test', testPackage],
    ['playwright', playwrightPackage],
    ['playwright-core', corePackage]
  ] as const
  const manifest = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'))
  if (manifest.devDependencies?.['@playwright/test'] !== version) throw new Error('Repository Playwright pin does not match hardware image.')
  for (const [packageName, file] of packages) {
    const pkg = JSON.parse(await fs.readFile(file, 'utf8'))
    if (pkg.name !== packageName || pkg.version !== version) throw new Error(`Resolved ${packageName} does not match ${version}.`)
  }
  const stat = await fs.lstat(device)
  if (!stat.isCharacterDevice() || stat.isSymbolicLink()) throw new Error('Hardware render node must be an actual character device.')
  metadata.deviceGid = stat.gid
  const networkInfo = JSON.parse(await command(['docker', 'network', 'inspect', network])) as Array<{ Labels?: Record<string, string> }>
  if (networkInfo.length !== 1 || networkInfo[0]?.Labels?.[label] !== owner) throw new Error('Hardware browser network ownership mismatch.')
  if (await command(['docker', 'container', 'inspect', '--format', '{{.Id}}', name], 30_000, true))
    throw new Error('Hardware browser container name already exists; refusing adoption.')
  if (!(await command(['docker', 'image', 'inspect', '--format', '{{.Id}}', image], 30_000, true)))
    await command(['docker', 'pull', '--platform=linux/amd64', image], 240_000)
  metadata.imageId = await command(['docker', 'image', 'inspect', '--format', '{{.Id}}', image])
  await fs.mkdir(directory, { recursive: true, mode: 0o700 })
  if (interrupted) throw new Error('Hardware launch cancelled.')
  creationAttempted = true
  containerId = await command([
    'docker',
    'create',
    '--platform=linux/amd64',
    '--name',
    name,
    '--label',
    `${label}=${owner}`,
    '--network',
    network,
    '--publish',
    '127.0.0.1::3000',
    '--user',
    '65532:65532',
    '--group-add',
    String(stat.gid),
    '--device',
    `${device}:${device}:rw`,
    '--cap-drop=ALL',
    '--security-opt=no-new-privileges',
    '--read-only',
    '--memory=2g',
    '--memory-swap=2g',
    '--cpus=8',
    '--pids-limit=256',
    '--shm-size=128m',
    '--tmpfs',
    '/tmp:rw,nosuid,nodev,size=1g,mode=1777',
    '--env',
    'HOME=/tmp',
    '--env',
    'PLAYWRIGHT_BROWSERS_PATH=/ms-playwright',
    '--entrypoint',
    'sleep',
    image,
    'infinity'
  ])
  if (!/^[a-f0-9]{64}$/.test(containerId)) throw new Error('Hardware container creation did not return an immutable ID.')
  metadata.containerId = containerId
  await command(['docker', 'start', containerId])
  for (const [packageName, file] of packages) await transfer(containerId, path.dirname(file), `/tmp/runner/node_modules/${packageName}`)
  metadata.browser = JSON.parse(await command(['docker', 'exec', containerId, 'node', '-e', browserInfoScript]))
  await command(['docker', 'exec', containerId, 'mkdir', '-p', '/tmp/runner/artifacts'])
  await command([
    'docker',
    'exec',
    '-d',
    containerId,
    'sh',
    '-c',
    'exec node /tmp/runner/node_modules/@playwright/test/cli.js run-server --host 0.0.0.0 --port 3000 --max-clients 1 --unsafe --artifacts-dir /tmp/runner/artifacts > /tmp/runner/server.log 2>&1'
  ])
  const published = await command(['docker', 'port', containerId, '3000/tcp'])
  if (!/^127\.0\.0\.1:\d+$/.test(published)) throw new Error('Hardware server must publish only on host loopback.')
  let endpoint = ''
  const deadline = Date.now() + 30_000
  while (Date.now() < deadline && !interrupted) {
    const log = await command(['docker', 'exec', containerId, 'cat', '/tmp/runner/server.log'])
    const match = log.match(/Listening on (ws:\/\/\S+)/)
    if (match) {
      const address = new URL(match[1]!)
      endpoint = `ws://${published}${address.pathname}${address.search}`
      break
    }
    await Bun.sleep(250)
  }
  if (!endpoint) throw new Error('Pinned hardware Playwright server did not become ready within 30 seconds.')
  const child = spawn(process.execPath, ['--no-env-file', path.join(root, 'server/scripts/run-e2e.ts'), ...args], {
    cwd: root,
    stdio: 'inherit',
    env: {
      ...process.env,
      PLAYWRIGHT_HARDWARE_WS_ENDPOINT: endpoint,
      PLAYWRIGHT_JSON_OUTPUT_FILE: path.join(directory, 'results.json'),
      PLAYWRIGHT_HTML_OUTPUT_DIR: path.join(directory, 'html-report'),
      PLAYWRIGHT_HTML_OPEN: 'never',
      PLAYWRIGHT_BLOB_OUTPUT_DIR: path.join(directory, 'blob-report'),
      PLAYWRIGHT_BLOB_OUTPUT_FILE: path.join(directory, 'blob-report/report.zip')
    }
  })
  active.add(child)
  try {
    const { promise, resolve, reject } = Promise.withResolvers<number>()
    child.once('error', reject)
    child.once('close', code => resolve(code ?? (interrupted || 1)))
    status = await promise
  } finally {
    active.delete(child)
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error))
  status = interrupted || 1
} finally {
  // Docker may have completed creation even if its client was interrupted.
  if (creationAttempted && !containerId) {
    try {
      const inspected = await command(['docker', 'container', 'inspect', '--format', `{{.Id}} {{index .Config.Labels "${label}"}}`, name], 30_000, true)
      const [id, actualOwner] = inspected.split(' ')
      if (id && actualOwner !== owner) {
        console.error('Refusing cleanup of a foreign hardware container.')
        status = status || 1
      } else if (id && /^[a-f0-9]{64}$/.test(id) && actualOwner === owner) {
        containerId = id
      }
    } catch (error) {
      console.error(error instanceof Error ? error.message : String(error))
      status = status || 1
    }
  }
  if (containerId) {
    try {
      await command([process.execPath, phaseRunner, 'snapshot', '--container', containerId])
    } catch (error) {
      console.error(`Hardware resource snapshot failed: ${error instanceof Error ? error.message : String(error)}`)
      status = status || 1
    } finally {
      try {
        await command(['docker', 'rm', '-f', containerId])
      } catch (error) {
        console.error(`Hardware container removal failed: ${error instanceof Error ? error.message : String(error)}`)
        status = status || 1
      }
    }
  }
  metadata.exitStatus = interrupted || status
  try {
    await fs.mkdir(directory, { recursive: true, mode: 0o700 })
    await fs.writeFile(path.join(directory, 'launcher.json'), `${JSON.stringify(metadata, null, 2)}\n`, { mode: 0o600 })
  } catch (error) {
    console.error(`Hardware metadata write failed: ${error instanceof Error ? error.message : String(error)}`)
    status = status || 1
  }
  process.removeListener('SIGINT', interrupt)
  process.removeListener('SIGTERM', terminate)
  process.exitCode = interrupted || status
}
